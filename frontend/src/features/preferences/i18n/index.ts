export const dictionaries: Record<Language, Record<string, string>> = { vi, en };

export type TranslationKey = keyof typeof vi;

const noopSubscribe = () => () => {};

export function useLanguage(): Language {
  const language = useUiStore((s) => s.language);
  const mounted = useSyncExternalStore(
    noopSubscribe,
    () => true,
    () => false
  );
  // Render the default language on the server to avoid hydration mismatches.
  return mounted ? language : "vi";
}

export function useT() {
  const language = useLanguage();
  return useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      let text = dictionaries[language][key] ?? key;
      if (vars) {
        for (const [name, value] of Object.entries(vars)) {
          text = text.split(`{${name}}`).join(String(value));
        }
      }
      return text;
    },
    [language]
  );
}
